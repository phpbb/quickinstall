	private function injectVotes(int $topicId): void
	{
		$db = $this->context->db;
		$result = $db->sql_query('SELECT poll_option_id FROM ' . POLL_OPTIONS_TABLE . '
			WHERE topic_id = ' . $topicId . '
			ORDER BY poll_option_id ASC');
		$options = [];
		while ($row = $db->sql_fetchrow($result))
		{
			$options[] = (int) $row['poll_option_id'];
		}
		$db->sql_freeresult($result);
		$voters = array_slice($this->posters, 0, 6);
		$distribution = [0, 0, 1, 1, 2, 3];
		$totals = array_fill_keys($options, 0);
		foreach ($voters as $index => $userId)
		{
			$optionId = $options[$distribution[$index]] ?? 0;
			if (!$optionId)
			{
				continue;
			}
			$db->sql_query('INSERT INTO ' . POLL_VOTES_TABLE . ' ' . $db->sql_build_array('INSERT', [
				'topic_id' => $topicId,
				'poll_option_id' => $optionId,
				'vote_user_id' => $userId,
				'vote_user_ip' => '127.0.0.1',
			]));
			$totals[$optionId]++;
		}
		foreach ($totals as $optionId => $total)
		{
			$db->sql_query('UPDATE ' . POLL_OPTIONS_TABLE . '
				SET poll_option_total = ' . $total . '
				WHERE topic_id = ' . $topicId . ' AND poll_option_id = ' . $optionId);
		}
		$db->sql_query('UPDATE ' . TOPICS_TABLE . ' SET poll_last_vote = ' . time() . ' WHERE topic_id = ' . $topicId);
	}

	private function createTopic(
		int $forumId,
		int $userId,
		string $label,
		string $message,
		int $topicType = POST_NORMAL,
		array $additional = [],
		array $poll = []
	): array
	{
		$db = $this->context->db;
		$subject = $this->context->prefix . $label;
		$result = $db->sql_query_limit(
			'SELECT topic_id, topic_first_post_id FROM ' . TOPICS_TABLE . "
				WHERE topic_title = '" . $db->sql_escape($subject) . "'",
			1
		);
		$row = $db->sql_fetchrow($result);
		$db->sql_freeresult($result);
		if ($row)
		{
			$topicId = (int) $row['topic_id'];
			$postId = (int) $row['topic_first_post_id'];
			$this->context->addId('topics', $topicId);
			$this->context->addId('posts', $postId);
			return ['topic_id' => $topicId, 'post_id' => $postId];
		}

		$this->context->switchUser($userId);
		$data = $this->postData($forumId, 0, $subject, $message);
		$data = array_merge($data, $additional);
		submit_post('post', $subject, $this->context->user->data['username'], $topicType, $poll, $data);
		$topicId = (int) ($data['topic_id'] ?? 0);
		$postId = (int) ($data['post_id'] ?? 0);
		if (!$topicId || !$postId)
		{
			throw new RuntimeException("Unable to create seed topic: $subject");
		}
		$this->context->addId('topics', $topicId);
		$this->context->addId('posts', $postId);
		return ['topic_id' => $topicId, 'post_id' => $postId];
	}

	private function createReply(
		int $topicId,
		int $forumId,
		int $userId,
		string $label,
		string $message,
		string $key
	): int
	{
		$db = $this->context->db;
		$suffix = strpos($key, 'page-') === 0 ? ' — reply ' . substr($key, 5) : '';
		$subject = $this->context->prefix . 'Re: ' . $label . $suffix;
		$result = $db->sql_query_limit(
			'SELECT post_id FROM ' . POSTS_TABLE . "
				WHERE topic_id = $topicId
					AND post_subject = '" . $db->sql_escape($subject) . "'",
			1
		);
		$postId = (int) $db->sql_fetchfield('post_id');
		$db->sql_freeresult($result);
		if ($postId)
		{
			$this->context->addId('posts', $postId);
			return $postId;
		}

		$this->context->switchUser($userId);
		$data = $this->postData($forumId, $topicId, $subject, $message);
		$poll = [];
		submit_post('reply', $subject, $this->context->user->data['username'], POST_NORMAL, $poll, $data);
		$postId = (int) ($data['post_id'] ?? 0);
		if (!$postId)
		{
			throw new RuntimeException("Unable to create seed reply: $subject");
		}
		$this->context->addId('posts', $postId);
		return $postId;
	}

	private function postData(int $forumId, int $topicId, string $subject, string $message): array
	{
		$db = $this->context->db;
		$uid = $bitfield = '';
		$options = 7;
		generate_text_for_storage($message, $uid, $bitfield, $options, true, true, true);
		$result = $db->sql_query_limit('SELECT forum_name FROM ' . FORUMS_TABLE . ' WHERE forum_id = ' . $forumId, 1);
		$forumName = (string) $db->sql_fetchfield('forum_name');
		$db->sql_freeresult($result);

		return [
			'forum_id' => $forumId,
			'topic_id' => $topicId,
			'icon_id' => 0,
			'topic_title' => $subject,
			'topic_time_limit' => 0,
			'poster_id' => (int) $this->context->user->data['user_id'],
			'enable_bbcode' => true,
			'enable_smilies' => true,
			'enable_urls' => true,
			'enable_sig' => true,
			'message' => $message,
			'message_md5' => md5($message),
			'bbcode_bitfield' => $bitfield,
			'bbcode_uid' => $uid,
			'post_edit_locked' => 0,
			'notify_set' => false,
			'notify' => false,
			'post_time' => time(),
			'forum_name' => $forumName,
			'enable_indexing' => true,
			'force_approved_state' => true,
		];
	}

	private function createMovedRedirect(int $forumId, int $targetTopicId): int
	{
		$db = $this->context->db;
		$subject = $this->context->prefix . 'Moved topic redirect';
		$result = $db->sql_query_limit(
			'SELECT topic_id FROM ' . TOPICS_TABLE . '
				WHERE forum_id = ' . $forumId . '
					AND topic_status = ' . ITEM_MOVED . '
					AND topic_moved_id = ' . $targetTopicId,
			1
		);
		$id = (int) $db->sql_fetchfield('topic_id');
		$db->sql_freeresult($result);
		if (!$id)
		{
			$db->sql_query('INSERT INTO ' . TOPICS_TABLE . ' ' . $db->sql_build_array('INSERT', [
				'forum_id' => $forumId,
				'icon_id' => 0,
				'topic_title' => $subject,
				'topic_poster' => $this->users['regular_3'],
				'topic_time' => time(),
				'topic_status' => ITEM_MOVED,
				'topic_type' => POST_NORMAL,
				'topic_moved_id' => $targetTopicId,
				'topic_visibility' => ITEM_APPROVED,
			]));
			$id = (int) $db->sql_nextid();
		}
		$this->context->addId('topics', $id);
		return $id;
	}

	private function addModeratorLog(
		int $userId,
		int $forumId,
		int $topicId,
		string $operation,
		array $data
	): void
	{
		$db = $this->context->db;
		$result = $db->sql_query_limit('SELECT log_id FROM ' . LOG_TABLE . "
			WHERE log_type = " . LOG_MOD . '
				AND forum_id = ' . $forumId . '
				AND topic_id = ' . $topicId . "
				AND log_operation = '" . $db->sql_escape($operation) . "'",
			1
		);
		$logId = (int) $db->sql_fetchfield('log_id');
		$db->sql_freeresult($result);
		if (!$logId)
		{
			$logId = (int) $this->context->container->get('log')->add(
				'mod',
				$userId,
				'127.0.0.1',
				$operation,
				false,
				array_merge(['forum_id' => $forumId, 'topic_id' => $topicId], $data)
			);
		}
		if (!$logId)
		{
			throw new RuntimeException("Unable to create development moderator log: $operation");
		}
		$this->context->addId('logs', $logId);
	}

	private function forumName(int $forumId): string
	{
		$result = $this->context->db->sql_query_limit(
			'SELECT forum_name FROM ' . FORUMS_TABLE . ' WHERE forum_id = ' . $forumId,
			1
		);
		$name = (string) $this->context->db->sql_fetchfield('forum_name');
		$this->context->db->sql_freeresult($result);
		return $name;
	}

	private function firstIcon(): int
	{
		$result = $this->context->db->sql_query_limit('SELECT icons_id FROM ' . ICONS_TABLE . ' ORDER BY icons_id ASC', 1);
		$id = (int) $this->context->db->sql_fetchfield('icons_id');
		$this->context->db->sql_freeresult($result);
		return $id;
	}

	private function nextPoster(): int
	{
		$id = $this->posters[$this->posterIndex % count($this->posters)];
		$this->posterIndex++;
		return $id;
	}
}
