	private $posterIndex = 0;

	public function seed(array $users, array $forums): array
	{
		$this->users = $users;
		$this->forums = $forums;
		$this->posters = $users['posters'];
		$items = [];
		$iconId = $this->firstIcon();

		$items['announcement'] = $this->createTopic(
			$forums['news'],
			$users['admin'],
			'Announcement topic',
			'This announcement is shown more prominently than a regular topic in this forum.',
			POST_ANNOUNCE
		);
		$items['sticky'] = $this->createTopic(
			$forums['news'],
			$users['admin_2'],
			'Sticky topic',
			'This sticky stays near the top of the topic list so important information is easy to find.',
			POST_STICKY
		);
		$items['normal'] = $this->createTopic(
			$forums['lobby'],
			$users['regular'],
			'Normal topic',
			'This is a regular topic with no special status. Members can read it and add replies normally.'
		);
		$items['locked'] = $this->createTopic(
			$forums['lobby'],
			$users['admin'],
			'Locked topic',
			'This topic has been locked. Members can still read it, but they cannot add new replies.'
		);
		$this->context->db->sql_query('UPDATE ' . TOPICS_TABLE . '
			SET topic_status = ' . ITEM_LOCKED . '
			WHERE topic_id = ' . $items['locked']['topic_id']);
		$this->addModeratorLog(
			$users['admin'],
			$forums['lobby'],
			$items['locked']['topic_id'],
			'LOG_LOCK',
			[$this->context->prefix . 'Locked topic']
		);
		$items['icon'] = $this->createTopic(
			$forums['lobby'],
			$users['regular_2'],
			'Topic with icon',
			'This regular topic has an icon beside its title so you can check how topic icons are displayed.',
			POST_NORMAL,
			['icon_id' => $iconId]
		);
		$items['global'] = $this->createTopic(
			$forums['lobby'],
			$users['moderator'],
			'Global announcement',
			'This global announcement can appear across the board instead of belonging to only one forum.',
			POST_GLOBAL
		);
		$items['moved_target'] = $this->createTopic(
			$forums['lobby'],
			$users['regular_3'],
			'Moved topic destination',
			'This is the destination of a moved topic. The original forum contains a redirect that points here.'
		);
		$items['moved_redirect'] = [
			'topic_id' => $this->createMovedRedirect($forums['read'], $items['moved_target']['topic_id']),
			'post_id' => 0,
		];
		$this->addModeratorLog(
			$users['moderator'],
			$forums['read'],
			$items['moved_target']['topic_id'],
			'LOG_MOVE',
			[$this->forumName($forums['read']), $this->forumName($forums['lobby'])]
		);

		$sectionNames = [
			'news' => 'News forum',
			'lobby' => 'Lobby forum',
			'read' => 'Read forum',
			'unread' => 'Unread forum',
			'parent' => 'Parent forum',
			'locked_forum' => 'Locked forum',
			'password' => 'Password-protected forum',
			'private' => 'Private forum',
			'icon' => 'Forum with icon',
			'child_a' => 'Child subforum A',
			'child_b' => 'Child subforum B',
		];
		foreach ($forums as $key => $forumId)
		{
			if (in_array($key, ['link', 'empty'], true))
			{
				continue;
			}
			for ($number = 1; $number <= 3; $number++)
			{
				$this->createTopic(
					$forumId,
					$this->nextPoster(),
					sprintf('%s topic %d', $sectionNames[$key] ?? ucfirst(str_replace('_', ' ', $key)), $number),
					sprintf(
						'This is topic %d in the %s. It has a short opening message and works like a regular discussion.',
						$number,
						$sectionNames[$key] ?? ucfirst(str_replace('_', ' ', $key))
					)
				);
			}
		}

		$items += $this->seedRichPosts();
		$items += $this->seedPolls();
		$this->context->setMeta('content', $items);
		$this->context->restoreUser();
		return $items;
	}

	public function seedVolume(array $forums, array $users, int $topicCount, int $replyCount): void
	{
		if (!$forums || !$users)
		{
			throw new RuntimeException('Seed preset requires forums and posting users.');
		}

		for ($topic = 1; $topic <= $topicCount; $topic++)
		{
			$forumId = $forums[($topic - 1) % count($forums)];
			$label = sprintf('Topic %03d', $topic);
			$item = $this->createTopic(
				$forumId,
				$users[($topic - 1) % count($users)],
				$label,
				sprintf('This is topic %d generated by the %s preset.', $topic, $this->context->preset)
			);

			for ($reply = 1; $reply <= $replyCount; $reply++)
			{
				$this->createReply(
					$item['topic_id'],
					$forumId,
					$users[($topic + $reply - 1) % count($users)],
					$label,
					sprintf('This is reply %d of %d in topic %d.', $reply, $replyCount, $topic),
					sprintf('page-%02d', $reply)
				);
			}

			if ($topic % 10 === 0)
			{
				$this->context->saveManifest();
				$GLOBALS['cache']->purge();
				gc_collect_cycles();
			}
		}
		$this->context->restoreUser();
	}

